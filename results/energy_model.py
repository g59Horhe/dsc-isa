#!/usr/bin/env python3
"""Energy per MAC from the gate-level runs (results/energy_runs.csv, written by energy_runs.py). Run from
results/. Energy of a run = total power x cycles x clock period, over the measured window; power is
OpenROAD's report_power on the routed netlist with extracted parasitics and the run's own switching
activity (Sky130 HD, tt 025C 1.80 V, zero-delay simulation: no glitch power).

Points: iso, both cores at 16 ns (both closed there); fast, each core at its fastest closed target of the
routed sweep (RV32IMC 11.5 ns, Xpulp 14.5 ns). Roles: O3 = C at -O3, hand = best hand-written RV32IMC
kernel, full = the complete extension (dot product, hardware loops, post-increment, clip).
Table 1: energy per MAC, and the energy ratio against the cycle ratio, base core against Xpulp core.
Table 2: the cost of carrying the extension unused: the same scalar binaries on the Xpulp core.
--latex PATH writes the paper's table (iso point)."""
import csv, collections, sys
MACS = {('dw3', '8x16x16'): 8 * 14 * 14 * 9, ('dw5', '8x16x16'): 8 * 12 * 12 * 25, ('pw', '16x16x8x8'): 16 * 16 * 8 * 8}
NAME = {'dw3': '3x3 depthwise', 'dw5': '5x5 depthwise', 'pw': '1x1 pointwise'}
rows = list(csv.DictReader(open('energy_runs.csv')))
R = {}
for r in rows:
    assert int(r['unannotated']) == 0 and int(r['cycles']) > 0, r
    e = float(r['p_total']) * int(r['cycles']) * float(r['period_ns']) * 1e-9
    R[(r['point'], r['core'], r['family'], r['data'], r['role'])] = dict(r, E=e, pj=e / MACS[(r['family'], r['shape'])] * 1e12,
                                                                      mw=float(r['p_total']) * 1e3, cyc=int(r['cycles']))
print(f"{len(rows)} runs; every run's gate-level cycles, bus counts and checksum equal the RTL run's (energy_runs.py asserts it); "
      f"every pin annotated: {all(int(r['unannotated']) == 0 for r in rows)}\n")
for point, lab in (('iso', 'both cores at 16 ns'), ('fast', 'RV32IMC at 11.5 ns, Xpulp at 14.5 ns')):
    print(f"## {point}: {lab}\n")
    print("| kernel | data | RV32IMC -O3 pJ/MAC | RV32IMC hand pJ/MAC | Xpulp full pJ/MAC | energy ratio vs -O3 | vs hand | cycle ratio vs -O3 | vs hand | power: -O3 / hand / full (mW) |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for (fam, data) in [('dw3', 'syn'), ('dw5', 'syn'), ('pw', 'syn'), ('dw3', 'real'), ('pw', 'real')]:
        k = lambda core, role: R.get((point, core, fam, data, role))
        o3, hd, fu = k('base', 'O3'), k('base', 'hand'), k('pulp', 'full')
        if not (o3 and hd and fu): continue
        print(f"| {NAME[fam]} | {data} | {o3['pj']:.1f} | {hd['pj']:.1f} | {fu['pj']:.1f} | {o3['E']/fu['E']:.2f}x | {hd['E']/fu['E']:.2f}x | "
              f"{o3['cyc']/fu['cyc']:.2f}x | {hd['cyc']/fu['cyc']:.2f}x | {o3['mw']:.2f} / {hd['mw']:.2f} / {fu['mw']:.2f} |")
    print(f"\ncarrying the extension unused ({point}): the same scalar binary on the Xpulp core against the RV32IMC core\n")
    print("| kernel | data | role | cycles RV32IMC / Xpulp | energy RV32IMC (nJ) | energy Xpulp (nJ) | Xpulp / RV32IMC |")
    print("|---|---|---|---|---|---|---|")
    for (fam, data) in [('dw3', 'syn'), ('dw5', 'syn'), ('pw', 'syn'), ('dw3', 'real'), ('pw', 'real')]:
        for role in ('O3', 'hand'):
            b, p = R.get((point, 'base', fam, data, role)), R.get((point, 'pulp', fam, data, role))
            if not (b and p): continue
            print(f"| {NAME[fam]} | {data} | {role} | {b['cyc']:,} / {p['cyc']:,} | {b['E']*1e9:.1f} | {p['E']*1e9:.1f} | {p['E']/b['E']:.3f} |")
    print()
if '--latex' in sys.argv:
    path = sys.argv[sys.argv.index('--latex') + 1]
    L = ["% generated by results/energy_model.py --latex; do not edit", "\\begingroup\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{lrrrrr}", "\\toprule",
         " & \\multicolumn{3}{c}{pJ/MAC} & \\multicolumn{2}{c}{energy ratio (cycle ratio)} \\\\",
         "kernel & \\texttt{-O3} & hand & full & vs \\texttt{-O3} & vs hand \\\\", "\\midrule"]
    for (fam, data) in [('dw3', 'real'), ('dw5', 'syn'), ('pw', 'real')]:
        o3, hd, fu = (R.get(('iso', c, fam, data, r)) for c, r in (('base', 'O3'), ('base', 'hand'), ('pulp', 'full')))
        if not (o3 and hd and fu): continue
        lab = {'dw3': '3\\x3 dw', 'dw5': '5\\x5 dw', 'pw': '1\\x1 pw'}[fam] + (' (synthetic)' if data == 'syn' else '')
        L.append(f"{lab} & {o3['pj']:.0f} & {hd['pj']:.0f} & {fu['pj']:.0f} & {o3['E']/fu['E']:.2f}\\x\\ ({o3['cyc']/fu['cyc']:.2f}\\x) & {hd['E']/fu['E']:.2f}\\x\\ ({hd['cyc']/fu['cyc']:.2f}\\x) \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\endgroup"]
    open(path, 'w').write("\n".join(L) + "\n"); print(f"wrote {path}")
