#!/usr/bin/env python3
"""Generate sw/pwconv_blk_asm.c and sw/pwconv_blk_simd_asm.c: hand-written pointwise 1x1 convolution for input
channel counts the register-resident kernels (sw/pwconv_asm.c, sw/pwconv_simd_asm.c; CI = 8 or 16) cannot hold
(review round R7, 2026-11-01). The input channels of a pixel are processed in blocks of BS: each block's
activations are loaded into registers and swept over all CO output channels; between blocks the int32 partial
sum of every output channel is stored to and reloaded from a CO-word buffer (psum), and the last block
requantises and stores the byte. The scalar kernel holds BS = 16 activations (one per register); the SIMD kernel
holds BS = min(CI, 64) activations as BS/4 words, so it blocks only above 64 input channels. Weights stay in the
standard [CO][CI] layout. Each block variant exists with RV32IMC control (XPULP_CTRL=0) and Xpulp control
(XPULP_CTRL=1: hardware loop over output channels, post-increment loads and stores). Run from the repository
root: python3 sw/gen_pwconv_blk_asm.py"""

KINDS = ('only', 'first', 'mid', 'last')   # only: one block (no partial sums); first: store; mid: load and store; last: load, requantise


def tail(kind, xp, n):
    """Partial-sum load at the top (mid, last), the store at the bottom, and the instruction count."""
    head, end = [], []
    if kind in ('mid', 'last'):
        head.append('LW_INC("%[acc]", "%[pp]", "4")' if (xp and kind == 'last') else '"lw %[acc],0(%[pp])\\n"'); n += 1
    if kind in ('only', 'last'):
        end += ['REQUANT_ASM("%[acc]", "%[t]", "%[u]")', 'SB_INC("%[acc]", "%[op]", "1")' if xp else '"sb %[acc],0(%[op])\\n"']; n = f"{n + 1}+RQ_N"
    else:
        end.append('SW_INC("%[acc]", "%[pp]", "4")' if xp else '"sw %[acc],0(%[pp])\\n"'); n += 1
    return head, end, n


def scalar_body(kind, xp):
    L = []
    lb = lambda i: (f'LB_INC("%[w{i%2}]", "%[wp]", "1")' if xp else f'"lb %[w{i%2}],{i}(%[wp])\\n"')
    fresh = kind in ('only', 'first')
    L.append(lb(0))
    for i in range(16):
        if i + 1 < 16: L.append(lb(i + 1))
        L.append('"mul %[acc],%[a0],%[w0]\\n"' if (i == 0 and fresh) else f'"mul %[t],%[a{i}],%[w{i%2}]\\n add %[acc],%[acc],%[t]\\n"')
    n = 16 + (31 if fresh else 32)
    if xp and kind != 'only': L.append('"addi %[wp],%[wp]," RQ_XS(CI) "-16\\n"'); n += 1
    head, end, n = tail(kind, xp, n)
    return head + L + end, n


def simd_body(kind, xp, nw):
    ld = lambda k: (f'LW_INC("%[w{k%2}]", "%[wp]", "4")' if xp else f'"lw %[w{k%2}],{4*k}(%[wp])\\n"')
    fresh = kind in ('only', 'first')
    L = [ld(0), ld(1)]
    for k in range(nw):
        L.append(f'DOTSP("%[acc]", "%[x0]", "%[w0]")' if (k == 0 and fresh) else f'SDOTSP("%[acc]", "%[x{k}]", "%[w{k%2}]")')
        if k + 2 < nw: L.append(ld(k + 2))
    n = 2 * nw
    if xp and kind != 'only': L.append(f'"addi %[wp],%[wp]," RQ_XS(CI) "-{4*nw}\\n"'); n += 1
    head, end, n = tail(kind, xp, n)
    return head + L + end, n


def func(kind, xp, regs, preload, body, n):
    req = kind in ('only', 'last'); scalar = regs[0].startswith('a')
    outs = ['[wp]"+r"(wp)'] + (['[op]"+r"(op)'] if req else []) + (['[pp]"+r"(pp)'] if kind != 'only' else []) + ['[acc]"=&r"(acc)']
    outs += (['[t]"=&r"(t)'] if (scalar or req) else []) + (['[u]"=&r"(u)'] if req else []) + ['[w0]"=&r"(w0)', '[w1]"=&r"(w1)']
    outs += [f'[{r}]"=&r"({r})' for r in regs]
    decl = "int acc" + (", t" if (scalar or req) else "") + (", u" if req else "") + "; unsigned int w0, w1; " + ("int " if scalar else "unsigned int ") + ", ".join(regs) + ";"
    loop_tail = '"addi %[wp],%[wp]," RQ_XS(CI) "\\n' + (' addi %[op],%[op],1\\n' if req else '') + (' addi %[pp],%[pp],4\\n' if kind != 'only' else '') + ' bne %[wp],%[wend],1b\\n"'
    lines = [f'#if XPULP_CTRL == {xp}', f'    {decl}', '    int cnt = CO;' if xp else '    const signed char *wend = wp + CO * CI;', '    asm volatile (']
    lines += [f'          {x}' for x in ((['RQ_INIT("%[u]")'] if req else []) + (['XPULP_ASM_BEGIN'] if xp else []) + preload
              + [f'HWLOOP0("%[cnt]", RQ_XS({n}+1))   /* body: {n} instructions */' if xp else '"1:\\n"'] + body + ([] if xp else [loop_tail]) + (['XPULP_ASM_END'] if xp else []))]
    lines += ['          : ' + ", ".join(outs[:8]) + ',', '            ' + ", ".join(outs[8:]),
              '          : [xp]"r"(xp_), ' + ('[cnt]"r"(cnt)' if xp else '[wend]"r"(wend)'), '          : "memory");', '#endif']
    return "\n".join(lines)


HDR = '''/* Pointwise 1x1 convolution, input channels in blocks -- hand-written {kind} inner loop.
 * Generated by sw/gen_pwconv_blk_asm.py; do not edit.
 *
 * {desc}
 * Between blocks the int32 partial sum of each output channel goes to psum[CO] and comes back
 * (one store, then one load and one store per further block); the last block requantises with the
 * shared requant.h and stores the byte. Weights in the standard [CO][CI] layout.
 * XPULP_CTRL=0: RV32IMC control (immediate-offset loads, addi + bne).
 * XPULP_CTRL=1: hardware loop over output channels, post-increment loads and stores.
 */
#include "pw_common.h"
#include "xpulp.h"
#ifndef XPULP_CTRL
#define XPULP_CTRL 0
#endif
{bsdef}
#define NB (CI / BS)
static int psum[CO] __attribute__((aligned(4)));
'''

DRIVER = '''
static void {name}(void) {{
    for (int p = 0; p < P; p++) {{
        const act_t *x = input[p]; out_t *op = &output[p][0];
#if NB == 1
        blk_only(x, &weight[0][0], op);
#else
        blk_first(x, &weight[0][0], psum);
        for (int b = 1; b < NB - 1; b++) blk_mid(x + b * BS, &weight[0][b * BS], psum);
        blk_last(x + (NB - 1) * BS, &weight[0][(NB - 1) * BS], psum, op);
#endif
    }}
}}
#ifndef NO_MAIN
int main(void) {{ BENCH_PAD(); init_data(); CYC_START(); {name}(); CYC_STOP(); return checksum(); }}
#endif
'''

SIG = {'only': 'const act_t *xp_, const signed char *wp, out_t *op', 'first': 'const act_t *xp_, const signed char *wp, int *pp',
       'mid': 'const act_t *xp_, const signed char *wp, int *pp', 'last': 'const act_t *xp_, const signed char *wp, int *pp, out_t *op'}


def write(path, kind_name, desc, bsdef, guard, variants, name):
    s = HDR.format(kind=kind_name, desc=desc, bsdef=bsdef) + guard
    for kind in KINDS:
        s += f'\nstatic inline __attribute__((always_inline)) void blk_{kind}({SIG[kind]}) {{\n'
        for cond, regs, preload, mk in variants:
            s += f'#if {cond}\n'
            for xp in (1, 0):
                body, n = mk(kind, xp); s += func(kind, xp, regs, preload, body, n) + '\n'
            s += '#endif\n'
        s += '}\n'
    s += DRIVER.format(name=name)
    open(path, 'w').write(s)


# ---------------- scalar: 16 activations per block, one per register ----------------
a16 = [f'a{i}' for i in range(16)]
write('sw/pwconv_blk_asm.c', 'scalar',
      'Each block of 16 input channels is held as 16 activation registers across all CO output channels;\n'
      ' * each output costs 16 weight loads, 16 multiplies and 15 or 16 adds per block.',
      '#define BS 16', '#if CI % 16 || CI < 32\n#error "pwconv_blk_asm: CI must be a multiple of 16, at least 32"\n#endif\n',
      [('1', a16, [f'LBA " %[a{i}],{i}(%[xp])\\n"' for i in range(16)], scalar_body)], 'pwconv_blk_asm')

# ---------------- SIMD: up to 64 activations per block, as 16 words ----------------
var = []
for nw in (8, 16):
    xs = [f'x{i}' for i in range(nw)]
    var.append((f'BS == {4*nw}', xs, [f'"lw %[x{i}],{4*i}(%[xp])\\n"' for i in range(nw)], (lambda nw: lambda kind, xp: simd_body(kind, xp, nw))(nw)))
write('sw/pwconv_blk_simd_asm.c', 'cv.dotsp.b',
      'Each block of BS = min(CI, 64) input channels is held as BS/4 activation words across all CO output\n'
      ' * channels; each output costs BS/4 aligned weight-word loads (two registers in turn, each loaded two\n'
      ' * instructions ahead of its use), one cv.dotsp.b or cv.sdotsp.b per word, per block.',
      '#if CI <= 64\n#define BS CI\n#else\n#define BS 64\n#endif',
      '#if CI % 32 || (CI > 64 && CI % 64)\n#error "pwconv_blk_simd_asm: CI must be 32 or 64, or a multiple of 64"\n#endif\n',
      var, 'pwconv_blk_simd_asm')
print("wrote sw/pwconv_blk_asm.c and sw/pwconv_blk_simd_asm.c")
