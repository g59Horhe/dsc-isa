#!/usr/bin/env python3
"""Extract real int8 weights and real uint8 activation crops from quantised
MobileNetV1 (mobilenet_v1_1.0_224_quant.tflite, 2018-08-02) run on
grace_hopper.jpg, and write C headers for the kernels' REAL_DATA mode.

Depthwise 3x3: op 5, MobilenetV1/Conv2d_3_depthwise (56x56x128, stride 1).
  Real requant multiplier M = s_in*s_w/s_out = 0.06054, within 3% of 2^-4,
  so the kernels use an arithmetic shift of 4.
Pointwise 1x1: op 2, MobilenetV1/Conv2d_1_pointwise (112x112, 32 -> 64).
  M = 0.03042, within 3% of 2^-5, shift 5. CI is cropped to 16 of 32 input
  channels (the hand kernels are generated for CI in {8,16}), so each output
  is a partial sum over the first 16 channels.
Activations are uint8 with zero point 0 (post-ReLU6); weights are uint8 with
a per-layer zero point and become int8 by subtracting it (values outside
int8 are clipped and counted). Output = clamp(acc >> shift, 0, 255), which
is ReLU6 in the quantised domain (255 * s_out = 6.0). Rounding is truncation.
Usage: venv python sw/real/gen_real_data.py <model> <image> <outdir>"""
import sys, numpy as np
def lcg_headers(out):
    """Same LCG data as the kernels' init_data, as uint8 activations, written as
    headers so the synthetic data can run through the REAL_DATA code path."""
    for CH, H, W in [(8, 16, 16), (16, 16, 16), (8, 32, 32), (32, 8, 8)]:
        st = 1
        def rnd():
            nonlocal st; st = (st * 1103515245 + 12345) & 0xFFFFFFFF; return ((st >> 16) & 0xFF) - 128
        a = np.zeros((CH, H, W), np.uint8); w = np.zeros((CH, 3, 3), np.int8)
        for c in range(CH):
            for y in range(H):
                for x in range(W): a[c, y, x] = (rnd() >> 2) & 0xFF
            for i in range(3):
                for j in range(3): w[c, i, j] = rnd() >> 3
        s_ = 0
        for c in range(CH):
            for oy in range(H - 2):
                for ox in range(W - 2):
                    acc = int((a[c, oy:oy+3, ox:ox+3].astype(np.int32) * w[c].astype(np.int32)).sum()) >> 4
                    s_ += max(0, min(255, acc))
        write_header(f"{out}/syn_dw3_{CH}x{H}x{W}.h", "dw3", [("real_input", "unsigned char", a), ("real_weight", "signed char", w)],
                     {"REAL_SHIFT": 4, "REAL_CHECKSUM": s_ & 0xFFFF}, f"LCG data (same generator as init_data) as uint8, shift 4, checksum {s_ & 0xFFFF}")
        print(f"  syn dw3 {CH}x{H}x{W}: checksum={s_ & 0xFFFF}")
    for CI, CO, H, W in [(16, 16, 8, 8), (8, 8, 16, 16), (16, 32, 8, 8), (16, 16, 16, 16)]:
        st = 1
        def rnd():
            nonlocal st; st = (st * 1103515245 + 12345) & 0xFFFFFFFF; return ((st >> 16) & 0xFF) - 128
        P = H * W; a = np.zeros((P, CI), np.uint8); w = np.zeros((CO, CI), np.int8)
        for p_ in range(P):
            for c in range(CI): a[p_, c] = (rnd() >> 2) & 0xFF
        for o in range(CO):
            for c in range(CI): w[o, c] = rnd() >> 3
        accs = (a.astype(np.int32) @ w.astype(np.int32).T) >> 5; s_ = int(np.clip(accs, 0, 255).sum()) & 0xFFFF
        write_header(f"{out}/syn_pw_{CI}x{CO}x{H}x{W}.h", "pw", [("real_input", "unsigned char", a), ("real_weight", "signed char", w)],
                     {"REAL_SHIFT": 5, "REAL_CHECKSUM": s_}, f"LCG data as uint8, shift 5, checksum {s_}")
        print(f"  syn pw {CI}x{CO}x{H}x{W}: checksum={s_}")
from PIL import Image
from ai_edge_litert.interpreter import Interpreter
model, image, out = sys.argv[1], sys.argv[2], sys.argv[3]
it = Interpreter(model_path=model, experimental_preserve_all_tensors=True); it.allocate_tensors()
inp = it.get_input_details()[0]
it.set_tensor(inp['index'], np.array(Image.open(image).convert('RGB').resize((224, 224)), dtype=np.uint8)[None]); it.invoke()
T = it.get_tensor_details(); ops = it._get_ops_details()
def tensor(i): return it.get_tensor(i), T[i]
def weights_int8(i):
    w, d = tensor(i); zp = d['quantization'][1]; wi = w.astype(np.int32) - zp
    clipped = int(((wi < -128) | (wi > 127)).sum()); return np.clip(wi, -128, 127).astype(np.int8), d['quantization'][0], clipped
def write_header(path, name, arrays, defines, comment):
    with open(path, 'w') as f:
        f.write(f"/* Generated by sw/real/gen_real_data.py. {comment} */\n")
        for k, v in defines.items(): f.write(f"#define {k} {v}\n")
        for aname, ctype, arr in arrays:
            flat = arr.flatten(); f.write(f"static const {ctype} {aname}[{flat.size}] = {{\n")
            for i in range(0, flat.size, 24): f.write("  " + ",".join(str(int(x)) for x in flat[i:i+24]) + ",\n")
            f.write("};\n")
lcg_headers(out)
# ---------------- one depthwise-separable block: op 1 (dw 3x3) -> op 2 (pw 1x1) ----------------
# MobilenetV1 Conv2d_1_depthwise (112x112x32) feeding Conv2d_1_pointwise (32 -> 64).
# Crop: channels 0..15, 16x16 input window -> 14x14 x 16 depthwise output -> pointwise
# with CI = 16 (channels 0..15 of 32, partial sum) and CO = 16. Depthwise multiplier
# M = 0.292 is 14% below 2^-2; shift 2 is used and the error noted. Pointwise shift 5.
op1, op2 = ops[1], ops[2]; assert op1['op_name'] == 'DEPTHWISE_CONV_2D' and op2['op_name'] == 'CONV_2D'
a1, ad1 = tensor(op1['inputs'][0]); w1, ws1, c1 = weights_int8(op1['inputs'][1]); o1q = T[op1['outputs'][0]]['quantization']
w2, ws2, c2 = weights_int8(op2['inputs'][1]); o2q = T[op2['outputs'][0]]['quantization']
M1 = ad1['quantization'][0] * ws1 / o1q[0]; M2 = o1q[0] * ws2 / o2q[0]
print(f"block: dw M={M1:.4f} (2^-2 {(2**-2/M1-1)*100:+.0f}%) clipped={c1}; pw M={M2:.4f} (2^-5 {(2**-5/M2-1)*100:+.0f}%) clipped={c2}")
CH, H, W, CO = 16, 16, 16, 16; OH, OW = H - 2, W - 2; P = OH * OW
a = np.ascontiguousarray(a1[0][:H, :W, :CH].transpose(2, 0, 1)); wk = np.ascontiguousarray(w1[0][:, :, :CH].transpose(2, 0, 1)); wp = np.ascontiguousarray(w2[:CO, 0, 0, :CH])
dwo = np.zeros((CH, OH, OW), np.int64)
for c in range(CH):
    for oy in range(OH):
        for ox in range(OW): dwo[c, oy, ox] = (a[c, oy:oy+3, ox:ox+3].astype(np.int64) * wk[c].astype(np.int64)).sum() >> 2
dwo = np.clip(dwo, 0, 255); s1 = int(dwo.sum()) & 0xFFFF
x = dwo.transpose(1, 2, 0).reshape(P, CH)                      # channel-last
accs = (x.astype(np.int64) @ wp.astype(np.int64).T) >> 5; pwo = np.clip(accs, 0, 255); s2 = int(pwo.sum()) & 0xFFFF
print(f"  block 16x16x16 -> 14x14 -> 16: dw checksum={s1} (zeros {(dwo==0).mean():.0%}, sat {(dwo==255).mean():.1%}), pw checksum={s2} (zeros {(pwo==0).mean():.0%}, sat {(pwo==255).mean():.1%})")
write_header(f"{out}/block_16x16x16_16.h", "block", [("real_input", "unsigned char", a), ("real_weight", "signed char", wk), ("pw_real_weight", "signed char", wp)],
             {"REAL_SHIFT": 2, "PW_REAL_SHIFT": 5, "REAL_CHECKSUM": s1, "PW_REAL_CHECKSUM": s2}, f"MobilenetV1 Conv2d_1 depthwise+pointwise block, channels 0..15, 16x16 crop; dw checksum {s1}, pw checksum {s2}")
# ---------------- depthwise 3x3, op 5 ----------------
op = ops[5]; assert op['op_name'] == 'DEPTHWISE_CONV_2D'
act, ad = tensor(op['inputs'][0]); w, ws, wclip = weights_int8(op['inputs'][1]); outq = T[op['outputs'][0]]['quantization']
M = ad['quantization'][0] * ws / outq[0]; print(f"dw3x3: act {act.shape} zp={ad['quantization'][1]} w {w.shape} scale={ws:.5f} clipped={wclip} M={M:.5f} -> shift 4 (2^-4={2**-4:.5f}, {(2**-4/M-1)*100:+.1f}%)")
act = act[0]; w = w[0]   # act: H W C ; w: 3 3 C
for CH, H, W in [(8, 16, 16), (16, 16, 16), (8, 32, 32), (32, 8, 8)]:
    a = np.ascontiguousarray(act[:H, :W, :CH].transpose(2, 0, 1))        # C H W
    wk = np.ascontiguousarray(w[:, :, :CH].transpose(2, 0, 1))            # C 3 3
    # reference checksum with the kernels' arithmetic
    OH, OW = H - 2, W - 2; s = 0; sat_hi = 0; sat_lo = 0; outs = []
    for c in range(CH):
        for oy in range(OH):
            for ox in range(OW):
                acc = int((a[c, oy:oy+3, ox:ox+3].astype(np.int32) * wk[c].astype(np.int32)).sum()) >> 4
                sat_hi += acc > 255; sat_lo += acc < 0; v = max(0, min(255, acc)); outs.append(v); s += v
    outs = np.array(outs); n = CH * OH * OW
    print(f"  dw3 {CH}x{H}x{W}: checksum={s & 0xFFFF} out mean={outs.mean():.1f} zeros={(outs==0).mean():.1%} sat255={sat_hi/n:.1%} neg->0={sat_lo/n:.1%} act mean={a.mean():.1f} act zeros={(a==0).mean():.1%} |w| mean={np.abs(wk).mean():.1f} max={np.abs(wk).max()}")
    write_header(f"{out}/dw3_{CH}x{H}x{W}.h", "dw3", [("real_input", "unsigned char", a), ("real_weight", "signed char", wk)],
                 {"REAL_SHIFT": 4, "REAL_CHECKSUM": s & 0xFFFF}, f"MobilenetV1 Conv2d_3_depthwise, channels 0..{CH-1}, crop {H}x{W} at (0,0), checksum {s & 0xFFFF}")
# ---------------- pointwise 1x1, op 2 ----------------
op = ops[2]; assert op['op_name'] == 'CONV_2D'
act, ad = tensor(op['inputs'][0]); w, ws, wclip = weights_int8(op['inputs'][1]); outq = T[op['outputs'][0]]['quantization']
M = ad['quantization'][0] * ws / outq[0]; print(f"pw1x1: act {act.shape} w {w.shape} scale={ws:.5f} clipped={wclip} M={M:.5f} -> shift 5 (2^-5={2**-5:.5f}, {(2**-5/M-1)*100:+.1f}%)")
act = act[0]; w = w[:, 0, 0, :]   # act: H W C ; w: CO CI
for CI, CO, H, W in [(16, 16, 8, 8), (8, 8, 16, 16), (16, 32, 8, 8), (16, 16, 16, 16)]:
    a = np.ascontiguousarray(act[:H, :W, :CI].reshape(H * W, CI)); wk = np.ascontiguousarray(w[:CO, :CI])
    accs = (a.astype(np.int32) @ wk.astype(np.int32).T) >> 5
    outs = np.clip(accs, 0, 255); s = int(outs.sum()) & 0xFFFF
    print(f"  pw {CI}x{CO}x{H}x{W}: checksum={s} out mean={outs.mean():.1f} zeros={(outs==0).mean():.1%} sat255={(accs>255).mean():.1%} neg->0={(accs<0).mean():.1%} act mean={a.mean():.1f} |w| mean={np.abs(wk).mean():.1f} max={np.abs(wk).max()}")
    write_header(f"{out}/pw_{CI}x{CO}x{H}x{W}.h", "pw", [("real_input", "unsigned char", a), ("real_weight", "signed char", wk)],
                 {"REAL_SHIFT": 5, "REAL_CHECKSUM": s}, f"MobilenetV1 Conv2d_1_pointwise, in channels 0..{CI-1}, out channels 0..{CO-1}, crop {H}x{W} at (0,0), checksum {s}")
